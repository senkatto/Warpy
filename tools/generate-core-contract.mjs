import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = resolve(repositoryRoot, 'shared/core-contract.json');
const desktopPath = resolve(repositoryRoot, 'desktop-tauri/src/generated/core-contract.js');
const androidPath = resolve(
  repositoryRoot,
  'app/src/main/java/com/warpy/app/vpn/generated/CoreContract.kt',
);
const source = readFileSync(sourcePath, 'utf8').replace(/\r\n/g, '\n');
const contract = JSON.parse(source);
const digest = createHash('sha256').update(source).digest('hex');

function quotedList(values) {
  return values.map(value => `"${value}"`).join(', ');
}

const desktop = `// Generated by tools/generate-core-contract.mjs. Do not edit.\n`
  + `export const CORE_CONTRACT_SHA256 = '${digest}';\n`
  + `export const CORE_CONTRACT = Object.freeze(${JSON.stringify(contract, null, 2)});\n`;

const android = `// Generated by tools/generate-core-contract.mjs. Do not edit.\n`
  + `package com.warpy.app.vpn.generated\n\n`
  + `internal object CoreContract {\n`
  + `    const val SOURCE_SHA256 = "${digest}"\n`
  + `    const val VERSION = ${contract.version}\n`
  + `    val protocols = setOf(${quotedList(contract.protocols)})\n`
  + `    val transports = setOf(${quotedList(contract.transports)})\n\n`
  + `    object Tags {\n`
  + Object.entries(contract.tags)
    .map(([key, value]) => `        const val ${key} = "${value}"`)
    .join('\n')
  + `\n    }\n\n`
  + `    object Dns {\n`
  + `        const val remoteServer = "${contract.dns.remoteServer}"\n`
  + `        const val remotePort = ${contract.dns.remotePort}\n`
  + `        const val remotePath = "${contract.dns.remotePath}"\n`
  + `        const val remoteTlsServerName = "${contract.dns.remoteTlsServerName}"\n`
  + `        const val localServer = "${contract.dns.localServer}"\n`
  + `        const val localPort = ${contract.dns.localPort}\n`
  + `        const val strategy = "${contract.dns.strategy}"\n`
  + `    }\n\n`
  + `    object Routing {\n`
  + `        val russianDomainSuffixes = listOf(${quotedList(contract.routing.russianDomainSuffixes)})\n`
  + `        val healthDomainSuffixes = listOf(${quotedList(contract.routing.healthDomainSuffixes)})\n`
  + `        const val blockQuicOnlyWhenEnabled = ${contract.routing.blockQuicOnlyWhenEnabled}\n`
  + `    }\n\n`
  + `    object Android {\n`
  + `        const val interfaceName = "${contract.platforms.android.interfaceName}"\n`
  + `        val addresses = listOf(${quotedList(contract.platforms.android.addresses)})\n`
  + `        const val localDnsTag = "${contract.platforms.android.localDnsTag}"\n`
  + `        const val localDnsType = "${contract.platforms.android.localDnsType}"\n`
  + `        const val stack = "${contract.platforms.android.stack}"\n`
  + `        const val strictRoute = ${contract.platforms.android.strictRoute}\n`
  + `        const val defaultMtu = ${contract.platforms.android.defaultMtu}\n`
  + `        const val xhttpDefaultMode = "${contract.platforms.android.xhttpDefaultMode}"\n`
  + `    }\n\n`
  + `    object Windows {\n`
  + `        const val interfaceName = "${contract.platforms.windows.interfaceName}"\n`
  + `        val addresses = listOf(${quotedList(contract.platforms.windows.addresses)})\n`
  + `        const val stack = "${contract.platforms.windows.stack}"\n`
  + `        const val strictRoute = ${contract.platforms.windows.strictRoute}\n`
  + `        const val defaultMtu = ${contract.platforms.windows.defaultMtu}\n`
  + `        const val xhttpDefaultMode = "${contract.platforms.windows.xhttpDefaultMode}"\n`
  + `    }\n`
  + `}\n`;

const outputs = [[desktopPath, desktop], [androidPath, android]];
if (process.argv.includes('--check')) {
  const stale = outputs.filter(([path, expected]) => {
    try {
      return readFileSync(path, 'utf8').replace(/\r\n/g, '\n') !== expected;
    } catch {
      return true;
    }
  });
  if (stale.length) {
    console.error(`Generated core contract is stale: ${stale.map(([path]) => path).join(', ')}`);
    process.exit(1);
  }
} else {
  outputs.forEach(([path, content]) => writeFileSync(path, content, 'utf8'));
}
